<?php

declare(strict_types=1);

namespace App\Support;

use App\Models\CompanyProfile;
use Illuminate\Support\Str;

/**
 * تطبيع اسم جهة العمل — مفتاحُ المطابقة في عمى صاحب العمل (ADR-004).
 *
 * ★ لماذا نحتاجه أصلاً؟
 *
 *   الموظّف يكتب اسم شركته **نصّاً حرّاً** قبل أن تسجّل شركتُه في المنصّة
 *   أصلاً. فلو اكتفينا بالمطابقة بالمعرّف (`current_employer_company_id`)
 *   لبقي كلُّ من كتب اسم شركته قبل تسجيلها مكشوفاً لها يوم تسجّل.
 *
 *   والنصّ الحرّ لا يُطابَق حرفياً: «شركة الخليج للتقنية ذ.م.م» و«الخليج
 *   للتقنية» شركةٌ واحدة، ومسافةٌ أو همزةٌ أو «ش.م.ق» كافيةٌ لتُفلت الحجب.
 *
 * ⚠️ التطبيع **متسامح عمداً**: أن نحجب ملفّاً عن شركةٍ ليست صاحبةَ عمله
 *    خسارةُ فرصةٍ تجارية، وأن نكشفه لصاحب عمله كارثةٌ قد تُفقده وظيفته.
 *    العطب يُغلق الباب.
 */
final class EmployerName
{
    /**
     * الصيغ القانونية واللواحق التجارية — لا تُميّز شركةً من أخرى.
     *
     * تُحذف قبل المقارنة: «مجموعة الخليج» و«الخليج ذ.م.م» اسمٌ واحد لمن يقرأ.
     */
    private const NOISE = [
        'شركة', 'شركه', 'مؤسسة', 'مؤسسه', 'مجموعة', 'مجموعه', 'القابضة', 'القابضه',
        'ذمم', 'شمق', 'شمم', 'ومشاركوه', 'واولاده',
        'company', 'co', 'corp', 'corporation', 'ltd', 'limited', 'llc', 'wll',
        'inc', 'plc', 'group', 'holding', 'holdings', 'est', 'establishment',
    ];

    /**
     * مفتاحُ مطابقةٍ مستقرّ، أو `null` إن لم يبقَ من الاسم شيءٌ يُميّز.
     *
     * ★ الفراغ يعود `null` لا `''`: مفتاحٌ فارغ يُطابق كلَّ مفتاحٍ فارغ آخر،
     *   فيحجب ملفّ من كتب «شركة» عن كل من كتب «مؤسسة». لا مفتاحَ خيرٌ من
     *   مفتاحٍ يُطابق الجميع.
     */
    public static function key(?string $name): ?string
    {
        if ($name === null || trim($name) === '') {
            return null;
        }

        $text = Str::lower(Str::squish($name));

        // التشكيل والتطويل: لا يُنطقان ولا يُميّزان.
        $text = preg_replace('/[\x{064B}-\x{0652}\x{0640}]/u', '', $text) ?? $text;

        // توحيد الحروف التي يتساهل الناس في كتابتها: أإآٱ ← ا، ى ← ي، ة ← ه.
        $text = strtr($text, [
            'أ' => 'ا', 'إ' => 'ا', 'آ' => 'ا', 'ٱ' => 'ا',
            'ى' => 'ي', 'ة' => 'ه', 'ؤ' => 'و', 'ئ' => 'ي',
        ]);

        // كلُّ ما ليس حرفاً ولا رقماً يصير فاصلاً — النقطة في «ذ.م.م» والشرطة
        // في «الخليج-للتقنية» ليستا جزءاً من الاسم.
        $text = preg_replace('/[^\p{L}\p{N}]+/u', ' ', $text) ?? $text;

        $words = array_filter(
            explode(' ', trim($text)),
            static fn (string $word): bool => $word !== '' && ! in_array($word, self::NOISE, true),
        );

        // ★ الأحرف المفردة تُسقَط: «ذ.م.م» تتفكّك عند إسقاط النقاط إلى «ذ م م»
        //   لا إلى «ذمم»، فلا تُلقّطها قائمةُ الضجيج أعلاه. وكذلك «ش.م.ق»
        //   و«w.l.l». حرفٌ واحد لا يُميّز شركةً من أخرى.
        $meaningful = array_filter(
            $words,
            static fn (string $word): bool => Str::length($word) > 1,
        );

        // ⚠️ لكن لا نُفرغ الاسم: شركةٌ اسمُها «H&M» كلُّه أحرفٌ مفردة. لو
        //    أسقطناها لعاد `null` — فلا مفتاحَ لها، ولا حجبَ لموظّفيها. حين لا
        //    يبقى شيء، نُبقي ما كان.
        $key = implode('', $meaningful !== [] ? $meaningful : $words);

        return $key === '' ? null : Str::limit($key, 160, '');
    }

    /**
     * مفاتيح الشركة الواحدة — من اسمها القانوني واسمها التجاري معاً.
     *
     * الموظّف يعرف شركته بما يُكتب على بابها («طلبات») لا بما في سجلّها
     * التجاري («شركة الخدمات اللوجستية الحديثة ذ.م.م»). المفتاحان كلاهما
     * يحجب.
     *
     * @return list<string>
     */
    public static function keysOf(CompanyProfile $company): array
    {
        $keys = array_filter([
            self::key($company->legal_name),
            self::key($company->brand_name),
        ]);

        return array_values(array_unique($keys));
    }
}
